#!/usr/bin/env node
/**
 * scripts/deliver.mjs — upload full-resolution originals to a GitHub Release.
 *
 * Requires the GitHub CLI, authenticated:   gh auth login
 *
 * Usage:
 *   node scripts/deliver.mjs <originals-dir> --tag <release-tag> [options]
 *
 * Options:
 *   --title "…"     release title (default: the tag)
 *   --notes "…"     release notes
 *   --zip [name]    upload one ZIP instead of individual files
 *                   (per-photo download buttons then disappear; the gallery
 *                   shows one "Download all full-res" button instead)
 *   --ext jpg,tif   only upload these extensions (default: common RAW + jpeg)
 *
 * Examples:
 *   # individual assets → per-photo "Download full-res" buttons in the gallery
 *   node scripts/deliver.mjs ~/Pictures/chen/fullres --tag delivery --title "Chen wedding — originals"
 *
 *   # one ZIP → single download-all button
 *   node scripts/deliver.mjs ~/Pictures/chen/fullres --tag delivery --zip
 *
 * Re-running with the same tag updates the release in place (--clobber).
 * Files keep their original names, which is what lets CI match them to the
 * previews generated by scripts/previews.mjs.
 */
import { readdir, stat, mkdtemp } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import os from "node:os";
import path from "node:path";

const EXTS_DEFAULT = ["jpg", "jpeg", "png", "tif", "tiff", "dng", "cr3", "nef", "arw"];

const args = process.argv.slice(2);
const has = (name) => args.includes(`--${name}`);
const flag = (name, dflt) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : dflt;
};

const positional = args.filter((a, i) => !a.startsWith("--") && !args[i - 1]?.startsWith("--"));
const inDir = positional[0];
const tag = flag("tag");

if (!inDir || !tag) {
  console.error("usage: node scripts/deliver.mjs <originals-dir> --tag <release-tag> [--title …] [--notes …] [--zip [name]] [--ext jpg,tif]");
  process.exit(1);
}

function run(cmd, cmdArgs, opts = {}) {
  const res = spawnSync(cmd, cmdArgs, { stdio: "inherit", ...opts });
  if (res.status !== 0) {
    console.error(`\n[deliver] failed: ${cmd} ${cmdArgs[0]} (exit ${res.status})`);
    console.error("[deliver] is the GitHub CLI installed and authenticated?  gh auth status");
    process.exit(res.status ?? 1);
  }
}

function runQuiet(cmd, cmdArgs) {
  return spawnSync(cmd, cmdArgs, { stdio: "pipe" }).status === 0;
}

const exts = new Set(String(flag("ext", EXTS_DEFAULT.join(","))).split(",").map((e) => e.trim().toLowerCase().replace(/^\./, "")));

let files = (await readdir(inDir))
  .filter((f) => exts.has(path.extname(f).slice(1).toLowerCase()))
  .sort();

if (files.length === 0) {
  console.error(`[deliver] no matching files in ${inDir} (extensions: ${[...exts].join(", ")})`);
  process.exit(1);
}

const title = flag("title", tag);
const notes = flag("notes", "Full-resolution originals for this gallery.");
const totalBytes = (
  await Promise.all(files.map(async (f) => (await stat(path.join(inDir, f))).size))
).reduce((a, b) => a + b, 0);
const gb = (totalBytes / 1024 ** 3);
console.log(`[deliver] ${files.length} file(s), ~${gb.toFixed(2)} GB from ${inDir}`);

let payloads = files.map((f) => path.join(inDir, f));
const zipFlag = has("zip");
if (zipFlag) {
  const zipName = flag("zip", `${tag}.zip`);
  const tmp = await mkdtemp(path.join(os.tmpdir(), "deliver-"));
  const zipPath = path.join(tmp, zipName);
  console.log(`[deliver] zipping → ${zipName} (this can take a while)`);
  run("zip", ["-r", "-q", zipPath, ...files], { cwd: inDir });
  const zipSize = (await stat(zipPath)).size;
  if (zipSize > 2 * 1024 ** 3) {
    console.error(`[deliver] ZIP is ${(zipSize / 1024 ** 3).toFixed(2)} GB — GitHub caps a single asset at 2 GB. Split into multiple collections/ZIPs.`);
    process.exit(1);
  }
  payloads = [zipPath];
}
// Individual assets: GitHub caps a single asset at 2 GB.
for (const f of files) {
  const s = (await stat(path.join(inDir, f))).size;
  if (s > 2 * 1024 ** 3) {
    console.error(`[deliver] ${f} is ${(s / 1024 ** 3).toFixed(2)} GB — GitHub caps a single release asset at 2 GB.`);
    process.exit(1);
  }
}

const exists = runQuiet("gh", ["release", "view", tag]);
if (exists) {
  console.log(`[deliver] updating existing release "${tag}"`);
  run("gh", ["release", "upload", tag, ...payloads, "--clobber"]);
} else {
  console.log(`[deliver] creating release "${tag}"`);
  run("gh", ["release", "create", tag, ...payloads, "--title", title, "--notes", notes]);
}

console.log(`\n[deliver] done. Assets: gh release view ${tag}`);
console.log("[deliver] the nightly CI rebuild (or any push / manual Run workflow) will wire");
console.log("[deliver] the new download links into the gallery automatically.");
